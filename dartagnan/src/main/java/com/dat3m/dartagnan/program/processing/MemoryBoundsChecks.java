import org.sosy_lab.common.configuration.InvalidConfigurationException;

import java.util.ArrayList;
import java.util.Collection;
import java.util.List;

/*
    Instruments every load and store with an assertion that the accessed bytes lie within one of the memory objects
    the access may address (according to the alias analysis), i.e., within the object its pointer was derived from.
    This detects out-of-bounds accesses that UBSan's checks do not cover, e.g., overflows of heap buffers.
    Because the check is relative to the addressable objects, an overflow that lands inside an adjacent object is
    still detected.

    Only accesses of the input program (i.e., with a source location) are instrumented, not the ones of code
    generated by Dartagnan itself (e.g., for thread-local storage). Accesses are also not instrumented if the alias
    analysis finds no addressable object for them, or if one of their objects has unknown size.
    In the former case, the pointer may stem from broken external declarations whose accesses are irrelevant.
    In the latter case, the size of the object is not available as an expression.
    If the alias analysis reports all objects, the check is still sound (but cannot detect overflows into
    other objects), so these accesses are instrumented.
 */
public final class MemoryBoundsChecks implements ProgramProcessor {

    private static final Logger logger = LoggerFactory.getLogger(MemoryBoundsChecks.class);

    private static final TypeFactory types = TypeFactory.getInstance();
    private static final ExpressionFactory expressions = ExpressionFactory.getInstance();

    // Same message as for UBSan's invalid dereferences, so violations are reported as such.
    private static final String ERROR_MESSAGE = "invalid dereference";

    private final Configuration configuration;

    private MemoryBoundsChecks(Configuration config) {
        this.configuration = config;
    }

    public static MemoryBoundsChecks fromConfig(Configuration config) {
        return new MemoryBoundsChecks(config);
    }

    @Override
    public void run(Program program) {
        final AliasAnalysis alias;
        try {
            final Context analysisContext = Context.create();
            analysisContext.register(EventDomainRepository.class, EventDomainRepository.forProgram(program));
            analysisContext.register(BranchEquivalence.class, BranchEquivalence.fromConfig(program, configuration));
            analysisContext.register(ExecutionAnalysis.class, ExecutionAnalysis.fromConfig(program,
                    ProgressModel.defaultHierarchy(), analysisContext, configuration));
            analysisContext.register(ReachingDefinitionsAnalysis.class, ReachingDefinitionsAnalysis.fromConfig(program,
                    analysisContext, configuration));
            alias = AliasAnalysis.fromConfig(program, analysisContext, configuration, false);
        } catch (InvalidConfigurationException e) {
            logger.warn("Skipping memory bounds checks: {}", e.getMessage());
            return;
        }

        final List<MemoryCoreEvent> accesses = program.getThreadEvents(MemoryCoreEvent.class).stream()
                .filter(e -> e instanceof Load || (e instanceof Store && !(e instanceof Init)))
                .filter(e -> e.hasMetadata(SourceLocation.class))
                .toList();
        int numChecks = 0;
        for (MemoryCoreEvent access : accesses) {
            final Collection<MemoryObject> objects = alias.addressableObjects(access);
            if (objects.isEmpty() || !objects.stream().allMatch(o -> o != null && o.hasKnownSize())) {
                continue;
            }
            final Assert check = EventFactory.newAssert(inBounds(program, access, objects), ERROR_MESSAGE);
            check.copyAllMetadataFrom(access);
            access.insertBefore(check);
            numChecks++;
        }
        logger.info("Inserted {} memory bounds checks for {} memory accesses.", numChecks, accesses.size());
    }

    // OR_o (o <= addr && addr + accessSize <= o + size(o))
    private Expression inBounds(Program program, MemoryCoreEvent access, Collection<MemoryObject> objects) {
        final IntegerType archType = program.getArchType();
        final Expression address = expressions.makeCast(access.getAddress(), archType);
        final Expression accessSize = expressions.makeValue(types.getMemorySizeInBytes(access.getAccessType()), archType);
        final Expression accessEnd = expressions.makeAdd(address, accessSize);
        final List<Expression> cases = new ArrayList<>();
        for (MemoryObject object : objects) {
            final Expression base = expressions.makeCast(object, archType);
            final Expression end = expressions.makeAdd(base, expressions.makeCast(object.size(), archType));
            cases.add(expressions.makeAnd(
                    expressions.makeLTE(base, address, false),
                    expressions.makeLTE(accessEnd, end, false)));
        }
        return cases.stream().reduce(expressions::makeOr).orElseThrow();
    }
}
